BEGIN;

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS healthcare_facilities (
    facility_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_code TEXT UNIQUE,
    facility_name TEXT NOT NULL,
    facility_type TEXT,
    full_address TEXT NOT NULL,
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    location geometry(Point, 4326) GENERATED ALWAYS AS (
        ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)
    ) STORED,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS communities (
    community_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_name TEXT NOT NULL UNIQUE,
    full_address TEXT NOT NULL,
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    location geometry(Point, 4326) GENERATED ALWAYS AS (
        ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)
    ) STORED,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS patients (
    patient_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    illness TEXT NOT NULL,
    diagnosis_date DATE NOT NULL,
    address_text TEXT,
    community_name TEXT,
    diagnosing_facility_id BIGINT REFERENCES healthcare_facilities(facility_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS patient_locations (
    patient_location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id TEXT NOT NULL REFERENCES patients(patient_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    location geometry(Point, 4326) NOT NULL,
    location_source TEXT NOT NULL CHECK (
        location_source IN (
            'COMMUNITY_REFERENCE',
            'PATIENT_ADDRESS_GEOCODE',
            'FACILITY_PROXY',
            'MANUAL',
            'OTHER'
        )
    ),
    community_id BIGINT REFERENCES communities(community_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    facility_id BIGINT REFERENCES healthcare_facilities(facility_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    is_proxy BOOLEAN NOT NULL DEFAULT FALSE,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    resolved_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT patient_locations_community_source_check CHECK (
        location_source <> 'COMMUNITY_REFERENCE'
        OR (community_id IS NOT NULL AND is_proxy = FALSE)
    ),
    CONSTRAINT patient_locations_facility_proxy_check CHECK (
        (location_source = 'FACILITY_PROXY' AND facility_id IS NOT NULL AND is_proxy = TRUE)
        OR (location_source <> 'FACILITY_PROXY' AND is_proxy = FALSE)
    ),
    CONSTRAINT patient_locations_id_patient_unique
        UNIQUE (patient_location_id, patient_id)
);

CREATE TABLE IF NOT EXISTS clustering_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_start TIMESTAMPTZ NOT NULL,
    window_end TIMESTAMPTZ NOT NULL,
    window_days INTEGER NOT NULL DEFAULT 7 CHECK (window_days > 0),
    eps_meters DOUBLE PRECISION NOT NULL CHECK (eps_meters > 0),
    min_points INTEGER NOT NULL CHECK (min_points > 0),
    illness_filter TEXT,
    include_proxy_locations BOOLEAN NOT NULL DEFAULT TRUE,
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (
        status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')
    ),
    case_count INTEGER CHECK (case_count IS NULL OR case_count >= 0),
    proxy_case_count INTEGER CHECK (proxy_case_count IS NULL OR proxy_case_count >= 0),
    cluster_count INTEGER CHECK (cluster_count IS NULL OR cluster_count >= 0),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT clustering_runs_window_check CHECK (window_end > window_start),
    CONSTRAINT clustering_runs_counts_check CHECK (
        proxy_case_count IS NULL
        OR case_count IS NULL
        OR proxy_case_count <= case_count
    )
);

CREATE TABLE IF NOT EXISTS clustering_results (
    clustering_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES clustering_runs(run_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    patient_id TEXT NOT NULL REFERENCES patients(patient_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    patient_location_id BIGINT NOT NULL,
    cluster_id INTEGER,
    location_snapshot geometry(Point, 4326) NOT NULL,
    location_source_snapshot TEXT NOT NULL CHECK (
        location_source_snapshot IN (
            'COMMUNITY_REFERENCE',
            'PATIENT_ADDRESS_GEOCODE',
            'FACILITY_PROXY',
            'MANUAL',
            'OTHER'
        )
    ),
    is_proxy_snapshot BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT clustering_results_patient_location_fk
        FOREIGN KEY (patient_location_id, patient_id)
        REFERENCES patient_locations(patient_location_id, patient_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT clustering_results_proxy_snapshot_check CHECK (
        (location_source_snapshot = 'FACILITY_PROXY' AND is_proxy_snapshot = TRUE)
        OR (location_source_snapshot <> 'FACILITY_PROXY' AND is_proxy_snapshot = FALSE)
    ),
    CONSTRAINT clustering_results_run_patient_unique UNIQUE (run_id, patient_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS patient_locations_one_current_per_patient_idx
    ON patient_locations (patient_id)
    WHERE is_current = TRUE;

CREATE INDEX IF NOT EXISTS healthcare_facilities_location_gix
    ON healthcare_facilities USING GIST (location);

CREATE INDEX IF NOT EXISTS communities_location_gix
    ON communities USING GIST (location);

CREATE INDEX IF NOT EXISTS patient_locations_location_gix
    ON patient_locations USING GIST (location);

CREATE INDEX IF NOT EXISTS clustering_results_location_snapshot_gix
    ON clustering_results USING GIST (location_snapshot);

CREATE INDEX IF NOT EXISTS patients_diagnosis_illness_idx
    ON patients (diagnosis_date, illness);

CREATE INDEX IF NOT EXISTS patient_locations_patient_idx
    ON patient_locations (patient_id);

CREATE INDEX IF NOT EXISTS clustering_results_run_idx
    ON clustering_results (run_id);

CREATE OR REPLACE VIEW current_patient_spatial_points AS
SELECT
    p.patient_id,
    p.illness,
    p.diagnosis_date,
    pl.patient_location_id,
    pl.location,
    pl.location_source,
    pl.is_proxy,
    pl.community_id,
    pl.facility_id,
    pl.resolved_at
FROM patients AS p
JOIN patient_locations AS pl
    ON pl.patient_id = p.patient_id
   AND pl.is_current = TRUE;

COMMIT;
