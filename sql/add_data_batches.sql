BEGIN;

CREATE TABLE IF NOT EXISTS data_batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_name TEXT NOT NULL UNIQUE,
    source_name TEXT,
    is_synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    is_included BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE patients ADD COLUMN IF NOT EXISTS batch_id BIGINT
    REFERENCES data_batches(batch_id) ON UPDATE CASCADE ON DELETE RESTRICT;
ALTER TABLE clustering_runs ADD COLUMN IF NOT EXISTS included_batch_ids TEXT;
CREATE INDEX IF NOT EXISTS patients_batch_idx ON patients (batch_id);

CREATE OR REPLACE VIEW current_patient_spatial_points AS
SELECT p.patient_id, p.illness, p.diagnosis_date, pl.patient_location_id,
       pl.location, pl.location_source, pl.is_proxy, pl.community_id,
       pl.facility_id, pl.resolved_at, p.batch_id,
       COALESCE(db.is_included, TRUE) AS batch_is_included
FROM patients AS p
LEFT JOIN data_batches AS db ON db.batch_id = p.batch_id
JOIN patient_locations AS pl
  ON pl.patient_id = p.patient_id AND pl.is_current = TRUE;

COMMIT;
